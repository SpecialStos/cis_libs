// Stage 1.5, part 4: generate the two blocks in .luacheckrc that were guesses.
//
// THE DEFECT THIS REPLACES. The file carried `globals = { "Cis.*" }` with a
// comment explaining that this is "deliberately a PATTERN ... so the lint does
// not become a second thing to update when a module is renamed". luacheck has
// no wildcard syntax. The entry matched nothing, every `Cis*` global read as
// undefined, and luacheck reported 1971 of them. The intent was right and the
// mechanism was inert, which is the worst combination: a config that looks
// maintained and is not.
//
// The two generated blocks:
//   read_globals  every native and runtime function this repository calls,
//                 which are READ by the code and defined by FiveM.
//   globals       every global this repository DEFINES, read out of the source
//                 by build-libglobals.js.
//
// `--check` fails when the file has drifted, so the list cannot rot the way the
// wildcard did. A rename now requires one command, not an edit nobody makes.

const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const RC = path.join(root, '.luacheckrc')
const nativesDoc = JSON.parse(fs.readFileSync(path.join(root, 'tools', 'natives', 'natives.json'), 'utf8'))
const runtime = JSON.parse(fs.readFileSync(path.join(root, 'tools', 'natives', 'runtime.json'), 'utf8'))
const libDoc = JSON.parse(fs.readFileSync(path.join(root, 'tools', 'natives', 'lib-globals.json'), 'utf8'))

const BEGIN_RG = '-- BEGIN GENERATED read_globals'
const END_RG = '-- END GENERATED read_globals'
const BEGIN_G = '-- BEGIN GENERATED globals'
const END_G = '-- END GENERATED globals'

// Wrap at a readable width. One name per line would make this file enormous and
// the diff unreviewable; a very long single line is worse.
function wrap(names, indent, width = 92) {
  const lines = []
  let line = ''
  for (const n of names) {
    const piece = `"${n}",`
    if (line === '') line = indent + piece
    else if ((line + ' ' + piece).length <= width) line += ' ' + piece
    else { lines.push(line); line = indent + piece }
  }
  if (line) lines.push(line)
  return lines.join('\n')
}

function buildReadGlobals() {
  // A name this repository DEFINES must not also be declared read-only, or
  // luacheck reports its own assignment as W121 "setting a read-only global".
  // GetDistanceBetweenCoords is both a FiveM native and a cis_libs global, and
  // client/utils.lua assigns it, so it belongs in `globals` and nowhere else.
  const libGlobals = new Set(Object.keys(libDoc.globals))

  const names = new Set()
  for (const n of Object.keys(nativesDoc.natives)) if (!libGlobals.has(n)) names.add(n)
  for (const [realm, list] of Object.entries(runtime)) {
    if (realm === '$comment' || realm === 'std') continue
    for (const n of list) if (!libGlobals.has(n)) names.add(n)
  }
  const sorted = [...names].filter(n => /^[A-Za-z_][A-Za-z0-9_.]*$/.test(n)).sort()
  return [
    BEGIN_RG,
    '-- GENERATED by tools/gen-luacheck.js. Do not edit by hand.',
    '-- Regenerate with `npm run gen-luacheck`; CI runs it with --check.',
    '--',
    '-- Everything the FiveM runtime provides and the shipped code reads: the',
    '-- natives this repository calls, and the CfxLua scheduler, event,',
    '-- resource and type-construction functions. Realms are not encoded here --',
    '-- `npm run check-realms` is what enforces those. This list only stops',
    '-- luacheck reporting every FiveM call as an undefined global.',
    '--',
    '-- Names this repository defines itself are deliberately absent: a name in',
    '-- both lists would be read-only here and writable below, and luacheck',
    '-- resolves that to read-only.',
    '--',
    `-- ${sorted.length} names, from ${nativesDoc.counts.nativesUsed} natives in use.`,
    'read_globals = {',
    wrap(sorted, '    '),
    '}',
    END_RG,
  ].join('\n')
}

function buildGlobals() {
  const names = Object.keys(libDoc.globals).filter(n => /^[A-Za-z_][A-Za-z0-9_]*$/.test(n)).sort()
  // CIS_DUMP_TARGET is set by the caller, not by this repository: tools/gen-types.js
  // runs tools/lua-dump.lua under fengari and passes the file to read in a global,
  // because `arg` is a string there rather than a table.
  names.push('CIS_DUMP_TARGET')
  names.sort()
  return [
    BEGIN_G,
    '-- GENERATED by tools/gen-luacheck.js. Do not edit by hand.',
    '-- Regenerate with `npm run gen-luacheck`; CI runs it with --check.',
    '--',
    '-- What THIS repository defines and its own files hand to each other.',
    '-- Each shared script loads into every consumer VM, so a module can only',
    '-- reach its neighbour through a global. That is the design, not a leak,',
    '-- and it is the reason these names are declared at all.',
    '--',
    `-- ${names.length} names, read out of the source by build-libglobals.js.`,
    'globals = {',
    wrap(names, '    '),
    '}',
    END_G,
  ].join('\n')
}

function replaceBlock(text, begin, end, generated) {
  const b = text.indexOf(begin)
  const e = text.indexOf(end)
  if (b < 0 || e < 0 || e < b) throw new Error(`.luacheckrc has no ${begin} / ${end} markers`)
  return text.slice(0, b) + generated + text.slice(e + end.length)
}

// The test tree is a different kind of code and needs a different config.
//
// test/binding.lua:80 is `GetCurrentResourceName = function() ... end` and the
// next line is `exports = { cis_libs = EXPORTS }`. That is not sloppiness: the
// suite has no FiveM server, so it BUILDS one -- it implements the natives and
// the exports table as ordinary Lua functions and loads the real source on top.
// The root config calls those names read-only, because in shipped code nothing
// assigns them, and luacheck reported 179 W121 "setting a read-only global" for
// exactly the lines that make the test suite work.
//
// Suppressing 179 warnings one line at a time would be the blanket ignore the
// plan forbids, and would also hide a real accidental assignment. The honest
// version is a per-directory config that says what the directory is, so the
// finding disappears for the right reason and stays visible everywhere else.
function buildTestConfig() {
  const writable = new Set()
  for (const n of Object.keys(nativesDoc.natives)) writable.add(n)
  for (const [realm, list] of Object.entries(runtime)) {
    if (realm === '$comment') continue
    for (const n of list) writable.add(n)
  }
  for (const n of Object.keys(libDoc.globals)) writable.add(n)
  for (const n of ['TEST_CASES', 'CIS_TEST_FILES', 'CIS_API_REAL', 'SUITE_NAMES', 'CIS_DUMP_TARGET', 'CIS_LIVE_ENV']) writable.add(n)
  // Set by test/suite-runner.js so a suite can tell "driven by the JS runner"
  // from "driven by the stock-Lua entry point", which is the only thing that
  // distinguishes the two modes of test/run.lua.
  writable.add('CIS_SUITE_MODE')
  // The live harness's own shared table (test/live/cis_test_providers). Declared
  // here rather than discovered: build-libglobals.js reads cis_libs' manifest,
  // and the harness is a separate resource that is never shipped.
  writable.add('CisTestRing')
  // Natives the fake VM implements that the shipped code never calls, so they
  // are in neither natives.json nor the runtime list. A stub the code under
  // test does not exercise is still a stub, and still an assignment.
  for (const n of ['NetworkDoesNetworkIdExist', 'IsEntityDead', 'IsEntityAMissionEntity']) writable.add(n)
  const sorted = [...writable].filter(n => /^[A-Za-z_][A-Za-z0-9_.]*$/.test(n)).sort()

  return [
    '-- GENERATED by tools/gen-luacheck.js. Do not edit by hand.',
    '-- Regenerate with `npm run gen-luacheck`; CI runs it with --check.',
    '--',
    '-- Applies to the test tree only.',
    '--',
    '-- The suite runs with no FiveM server, so it builds one: it assigns the',
    '-- natives, the runtime functions and the exports table as ordinary Lua',
    '-- globals and then loads the real shipped source on top of them. Under the',
    '-- root config those names are read-only, which is correct for shipped code',
    '-- and wrong for a harness.',
    '--',
    '-- This is a statement about the directory, not a suppression. The same',
    '-- assignment in client/ or server/ is still a W121, and the 179 findings',
    '-- this removes were all of them being tests doing their job.',
    '',
    'std = "lua54"',
    'max_line_length = false',
    'codes = true',
    'unused = true',
    'unused_secondaries = true',
    'self = false',
    '-- Same reasoning for parameters. A stub for a native has to match the',
    '-- arity of that native, or the code under test passes the wrong number of',
    '-- arguments and the failure surfaces somewhere else entirely:',
    '--   function(hash, x, y, z) return entity end   -- CreateObject',
    '-- Six parameters, five unused, and every one of them has to be there.',
    '-- In shipped code an unused parameter is a real smell and stays reported.',
    'unused_args = false',
    '',
    `-- ${sorted.length} names writable in this directory.`,
    'globals = {',
    wrap(sorted, '    '),
    '}',
    '',
  ].join('\n')
}

function main() {
  const check = process.argv.includes('--check')
  const original = fs.readFileSync(RC, 'utf8').replace(/\r\n/g, '\n')
  let next = replaceBlock(original, BEGIN_RG, END_RG, buildReadGlobals())
  next = replaceBlock(next, BEGIN_G, END_G, buildGlobals())

  const testRc = path.join(root, 'test', '.luacheckrc')
  const testOriginal = fs.existsSync(testRc) ? fs.readFileSync(testRc, 'utf8').replace(/\r\n/g, '\n') : null
  const testNext = buildTestConfig()

  const rcStale = next !== original
  const testStale = testNext !== testOriginal

  if (!rcStale && !testStale) {
    console.log('.luacheckrc and test/.luacheckrc generated blocks are current')
    return
  }
  if (check) {
    if (rcStale) console.error('FAIL .luacheckrc generated blocks are stale. Run: npm run gen-luacheck')
    if (testStale) console.error('FAIL test/.luacheckrc is stale. Run: npm run gen-luacheck')
    process.exitCode = 1
    return
  }
  fs.writeFileSync(RC, next, 'utf8')
  fs.mkdirSync(path.dirname(testRc), { recursive: true })
  fs.writeFileSync(testRc, testNext, 'utf8')
  console.log('wrote .luacheckrc and test/.luacheckrc')
}

main()